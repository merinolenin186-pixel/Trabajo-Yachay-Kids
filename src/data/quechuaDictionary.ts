// Offline translation lookup engine
export function translateOffline(
  text: string,
  fromLang: 'es' | 'qu',
  dialect: 'chanka' | 'collao' = 'chanka'
): { translated: string; entry?: DictionaryEntry; suggestions: DictionaryEntry[] } {
  const cleanInput = text.trim().toLowerCase();
  if (!cleanInput) {
    return { translated: '', suggestions: [] };
  }

  // 1. Direct exact or substring match in dictionary
  let directMatch: DictionaryEntry | undefined;

  if (fromLang === 'es') {
    directMatch = QUECHUA_DICTIONARY.find(entry => {
      const sp = entry.spanish.toLowerCase();
      return (
        sp === cleanInput ||
        sp.split(/[\/,?¿!¡]/).some(part => part.trim() === cleanInput) ||
        cleanInput.includes(sp) ||
        sp.includes(cleanInput)
      );
    });
  } else {
    directMatch = QUECHUA_DICTIONARY.find(entry => {
      const qu = entry.quechua.toLowerCase();
      const chanka = entry.chankaVariation?.toLowerCase();
      const collao = entry.collaoVariation?.toLowerCase();
      return (
        qu === cleanInput ||
        chanka?.includes(cleanInput) ||
        collao?.includes(cleanInput) ||
        cleanInput.includes(qu)
      );
    });
  }

  // Find relevant suggestions based on query
  const suggestions = QUECHUA_DICTIONARY.filter(entry => {
    if (fromLang === 'es') {
      return (
        entry.spanish.toLowerCase().includes(cleanInput) ||
        entry.exampleSpanish.toLowerCase().includes(cleanInput)
      );
    } else {
      return (
        entry.quechua.toLowerCase().includes(cleanInput) ||
        entry.chankaVariation?.toLowerCase().includes(cleanInput) ||
        entry.collaoVariation?.toLowerCase().includes(cleanInput)
      );
    }
  }).slice(0, 6);

  if (directMatch) {
    if (fromLang === 'es') {
      const dialectChoice =
        dialect === 'chanka' && directMatch.chankaVariation
          ? directMatch.chankaVariation
          : dialect === 'collao' && directMatch.collaoVariation
          ? directMatch.collaoVariation
          : directMatch.quechua;
      return { translated: dialectChoice, entry: directMatch, suggestions };
    } else {
      return { translated: directMatch.spanish, entry: directMatch, suggestions };
    }
  }

  // Fallback translation if not found in preloaded dictionary
  return {
    translated: fromLang === 'es' ? '(Palabra no encontrada en el diccionario local)' : '(Manam tarisqachu)',
    suggestions,
  };
}
